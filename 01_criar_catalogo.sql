-- Execute no SQL Editor do projeto Mercearia da Esquina.
begin;
create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  nome text not null,
  preco numeric(10,2) not null check (preco >= 0),
  categoria text not null,
  status text not null default 'disponivel'
    check (status in ('disponivel', 'esgotado')),
  imagem_url text,
  created_at timestamptz not null default now()
);
alter table public.produtos enable row level security;
grant usage on schema public to anon, authenticated;
revoke all on public.produtos from anon, authenticated;
grant select on public.produtos to anon, authenticated;
drop policy if exists "Leitura publica do catalogo" on public.produtos;
create policy "Leitura publica do catalogo"
  on public.produtos for select to anon, authenticated
  using (true);
commit;
